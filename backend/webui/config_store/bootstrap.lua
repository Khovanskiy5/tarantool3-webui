    return table.concat({
        '#',
        '# Three-instance replicaset with raft election.',
        '# Generated by /bootstrap. Customize before production.',
        '#',
        credentials_block(),
        '',
        'iproto:',
        indent(1) .. 'advertise:',
        indent(2) .. 'peer:',
        indent(3) .. 'login: webui_peer',
        '',
        'replication:',
        indent(1) .. 'failover: election',
        '',
        'groups:',
        indent(1) .. 'default:',
        indent(2) .. 'replicasets:',
        indent(3) .. 'rs-1:',
        indent(4) .. 'instances:',
