        '',
    }, '\n')
end

M.TEMPLATES = {
    {
        name        = 'single-instance',
        title       = 'Single instance',
        description = 'One Tarantool process, no replication. Good for evaluation.',
        render      = tpl_single,
    },
    {
        name        = 'replicaset-3',
        title       = 'Three-instance replicaset',
        description = 'Raft election, one writer, two replicas. Production baseline.',
        render      = tpl_replicaset_3,
    },
    {
        name        = 'vshard-3x3',
        title       = 'Vshard cluster (3 storages + router)',
        description = 'Sharded layout skeleton; tune bucket counts before deploy.',
        render      = tpl_vshard_3x3,
    },
}

local function find_template(name)
    for _, t in ipairs(M.TEMPLATES) do
        if t.name == name then return t end
    end
    return nil
end

function M.list_templates()
    local out = {}
    for _, t in ipairs(M.TEMPLATES) do
        table.insert(out, {
            name        = t.name,
            title       = t.title,
            description = t.description,
        })
    end
    return out
end

-- Render a template by name. Returns (yaml, nil) on success, or
-- (nil, err_code) for an unknown template. Cluster name is
-- whitelist-validated to keep the YAML deterministic and to avoid
-- injection — the wizard inserts it into a comment header only.
function M.render(template_name, cluster_name)
    local tpl = find_template(template_name)
    if tpl == nil then
        return nil, 'TEMPLATE_NOT_FOUND'
    end
    if cluster_name ~= nil and type(cluster_name) ~= 'string' then
        return nil, 'INVALID_CLUSTER_NAME'
    end
    if cluster_name ~= nil
        and not cluster_name:match('^[%w][%w_%-%.]*$') then
        return nil, 'INVALID_CLUSTER_NAME'
    end
    return tpl.render(cluster_name)
end

-- ── status ──────────────────────────────────────────────────────────

-- Decide whether the bootstrap wizard should kick in. The decision
-- is intentionally conservative: a positive `needed=true` only when
-- BOTH the local config source is empty AND the etcd probe (when
-- configured) returns no `config` key. Any ambiguity returns
-- `needed=false` so the wizard never overwrites a live deployment.
--
-- Returns: { needed = bool, reason = string, source = "etcd"|"file"|"unknown" }
function M.status(opts)
    opts = opts or {}
    local local_yaml = opts.local_yaml
    local etcd       = opts.etcd_client

    if etcd ~= nil then
        local existing, _err = etcd:get('config')
        if existing ~= nil and existing.value ~= nil
            and #existing.value > 0 then
            return {
                needed = false,
                source = 'etcd',
                reason = 'etcd already holds a config key',
            }
        end
        -- existing == nil: get() returned nil — could be KEY_NOT_FOUND
        -- (good) or a transport error (ambiguous). Defer to the file
        -- check below; the operator sees the explicit reason text.
    end

    if local_yaml ~= nil and #local_yaml > 0 then
        return {
            needed = false,
            source = 'file',
            reason = 'local cluster.yaml is non-empty',
        }
    end

    return {
        needed = true,
        source = etcd ~= nil and 'etcd' or 'unknown',
        reason = 'no cluster config detected',
    }
end

return M
