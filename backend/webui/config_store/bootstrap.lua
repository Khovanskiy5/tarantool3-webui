local function tpl_vshard_3x3(_cluster_name)
    -- Skeleton only. A full vshard topology needs sharding.bucket_count
    -- and per-instance roles; ship the most common 3-router/3-storage
    -- layout as a starting point. Operators tune bucket counts.
    return table.concat({
        '#',
        '# Vshard 3x3 (three storage replicasets + routers).',
        '# Generated by /bootstrap. Customize before production.',
        '#',
        credentials_block(),
        '',
        'iproto:',
        indent(1) .. 'advertise:',
        indent(2) .. 'peer:',
        indent(3) .. 'login: webui_peer',
        '',
        'replication:',
        indent(1) .. 'failover: election',
        '',
        'sharding:',
        indent(1) .. 'bucket_count: 3000',
        '',
        'groups:',
        indent(1) .. 'storages:',
        indent(2) .. 'sharding: { roles: [storage] }',
        indent(2) .. 'replicasets:',
        indent(3) .. 'storage-1:',
        indent(4) .. 'instances:',
        instance('storage-1-a', 3301),
        indent(3) .. 'storage-2:',
        indent(4) .. 'instances:',
        instance('storage-2-a', 3302),
        indent(3) .. 'storage-3:',
        indent(4) .. 'instances:',
        instance('storage-3-a', 3303),
        indent(1) .. 'routers:',
        indent(2) .. 'sharding: { roles: [router] }',
        indent(2) .. 'replicasets:',
        indent(3) .. 'router-1:',
        indent(4) .. 'instances:',
        instance('router-1-a', 3311),
